// The chosen language, or the phone's language the first time the app opens.
export function getLang() {
  const chosen = getSettings().lang;
  if (LANGUAGES.some((l) => l.id === chosen)) return chosen;
  return /^zh/i.test(navigator.language || '') ? 'zh-Hant' : 'en';
}

export function locale() {
  return getLang() === 'zh-Hant' ? 'zh-TW' : 'en';
}

