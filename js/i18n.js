// t('key', { name: value }) → text in the current language.
export function t(key, vars = {}) {
  const entry = STRINGS[getLang()][key] ?? STRINGS.en[key] ?? key;
  if (typeof entry === 'function') return entry(vars.n);
  if (typeof entry !== 'string') return entry;
  return entry.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
